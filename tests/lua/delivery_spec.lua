local ns=...
local Ch,D,V,G=ns.Channel,ns.Delivery,ns.Validation,ns.Guild
local count=0
local function test(name,fn)local ok,err=pcall(fn);assert(ok,name..": "..tostring(err));count=count+1 end
local function eq(a,b)assert(a==b,tostring(a).." ~= "..tostring(b))end
local function actor(name)return{id=name.."-Forever",name=name,realm="Forever"}end
local a,b,z=actor("Lyra"),actor("Kaelan"),actor("Thorin")
local roster={[a.id]=a,[b.id]=b,[z.id]=z}
local function fresh(owner,root)return assert(Ch.New({guildId="guild:1",owner=owner},root or {},roster))end
local serial=0
local function envelope(from,kind,to,id)
    serial=serial+1;local e=Ch.Envelope(from,kind,"t"..serial,to.context.owner.id)
    e.notificationId=id;e.claimId="v";return e
end
local function receive(to,from,e)return Ch.Receive(to,e,from.context.owner.id,roster)end
local function state(from,to)serial=serial+1;return receive(to,from,assert(Ch.State(from,"s"..serial)))end
local function seeded()
    local x,y=fresh(a),fresh(b)
    assert(Ch.Change(x,"incident",{id="i",guildId="guild:1",enemy=actor("Enemy"),victim=a,occurredAt=100,source="observed",location={zone="Elwynn"}}))
    assert(state(x,y));assert(Ch.Change(y,"claim",{id="v",guildId="guild:1",enemyId="Enemy-Forever",avenger=b,occurredAt=200,incidentIds={"i"}}));assert(state(y,x))
    return x,y,ns.Notifications.List(x.session.db,a.id)[1].id
end
test("voluntary click persists queue and private choice atomically",function()
    local x,y,id=seeded();eq(V.Count(x.delivery.outbox),0);assert(Ch.Change(x,"thank",id))
    eq(x.delivery.outbox[id].status,"pending");assert(x.root.guildDelivery["guild:1"].outbox[id]);assert(ns.Notifications.All(x.session.db)[id].thanked)
    eq(Ch.Change(x,"thank",id),false)
end)
test("recipient receives durable thank, only correct ACK completes delivery",function()
    local x,y,id=seeded();Ch.Change(x,"thank",id);assert(receive(y,x,envelope(x,"thank",y,id)))
    eq(#D.View(y.delivery,y.session).notifications,1);eq(x.delivery.outbox[id].status,"pending")
    assert(receive(x,y,envelope(y,"thank_ack",x,id)));eq(x.delivery.outbox[id].status,"delivered")
    eq(#D.Pending(x.delivery,x.session),0)
end)
test("lost ACK and reload preserve pending and deduplicate recipient",function()
    local x,y,id=seeded();Ch.Change(x,"thank",id);receive(y,x,envelope(x,"thank",y,id))
    local alerts,v,t=D.Alerts(y.delivery,y.session);eq(#t,1);Ch.Commit(y,y.session,alerts)
    x=fresh(a,V.Copy(x.root));y=fresh(b,V.Copy(y.root))
    eq(x.delivery.outbox[id].status,"pending");assert(receive(y,x,envelope(x,"thank",y,id)))
    eq(V.Count(y.delivery.inbox),1);local _,_,again=D.Alerts(y.delivery,y.session);eq(#again,0)
    receive(x,y,envelope(y,"thank_ack",x,id));eq(x.delivery.outbox[id].status,"delivered")
end)
test("wrong author recipient claim and guild cannot forge a thank",function()
    local x,y,id=seeded();local stranger=fresh(z)
    local before=V.Copy(y.root)
    eq(receive(y,stranger,envelope(stranger,"thank",y,id)),false)
    local e=envelope(x,"thank",y,id);e.claimId="other";eq(receive(y,x,e),false)
    e=envelope(x,"thank",y,id);e.target=a.id;eq(receive(y,x,e),false)
    e=envelope(x,"thank",y,id);e.guildId="other";eq(receive(y,x,e),false)
    assert(V.Same(before,y.root))
end)
test("forged acknowledgement never marks delivered",function()
    local x,y,id=seeded();Ch.Change(x,"thank",id);local stranger=fresh(z)
    eq(receive(x,stranger,envelope(stranger,"thank_ack",x,id)),false)
    local e=envelope(y,"thank_ack",x,id);e.claimId="wrong";eq(receive(x,y,e),false)
    eq(x.delivery.outbox[id].status,"pending")
end)
test("thank before state rejected then accepted after catchup",function()
    local x,y,id=seeded();local late=fresh(b)
    eq(receive(late,x,envelope(x,"thank",late,id)),false);eq(V.Count(late.delivery.inbox),0)
    state(x,late);assert(receive(late,x,envelope(x,"thank",late,id)))
end)
test("read received thank remains read after retry and reload",function()
    local x,y,id=seeded();receive(y,x,envelope(x,"thank",y,id));assert(Ch.Change(y,"read","thanks:"..id))
    receive(y,x,envelope(x,"thank",y,id));y=fresh(b,V.Copy(y.root))
    assert(D.View(y.delivery,y.session).notifications[1].read)
end)
test("catchup alert once per victim persists, read backlog stays quiet",function()
    local x,y,id=seeded();local data,v,t=D.Alerts(x.delivery,x.session);eq(#v,1);eq(#t,0)
    assert(Ch.Commit(x,x.session,data));x=fresh(a,V.Copy(x.root))
    local _,again=D.Alerts(x.delivery,x.session);eq(#again,0)
    local other=select(1,seeded());assert(Ch.Change(other,"read",id));local _,unread=D.Alerts(other.delivery,other.session);eq(#unread,0)
end)
test("no private delivery or read state exported with shared ledger",function()
    local x,y,id=seeded();Ch.Change(x,"thank",id)
    local e=assert(Ch.State(x,"export"));eq(e.message.notificationState,nil);eq(e.message.guildDelivery,nil);eq(e.delivery,nil)
end)
test("legacy local thanks require a new explicit click",function()
    local x,y,id=seeded();assert(ns.Notifications.Thank(x.session.db,id,a.id))
    x.session.notificationState=V.Copy(x.session.db.notificationState);Ch.Commit(x,x.session)
    x=fresh(a,V.Copy(x.root));eq(#D.Pending(x.delivery,x.session),0);eq(D.View(x.delivery,x.session).notifications[1].deliveryStatus,"local")
    assert(Ch.Change(x,"thank",id));eq(x.delivery.outbox[id].status,"pending")
end)
test("self thanks rejected without altering choice",function()
    local x,y,id=seeded();local self=fresh(a);state(x,self)
    self.session.claims={};self.session.db=ns.Store.New("guild:1");self.session.incidents={}
    G.AddIncident(self.session,{id="self",guildId="guild:1",enemy=actor("Enemy"),victim=a,occurredAt=100,source="observed",location={zone="Elwynn"}})
    G.Claim(self.session,{id="own",guildId="guild:1",enemyId="Enemy-Forever",avenger=a,occurredAt=200,incidentIds={"self"}})
    local note=ns.Notifications.List(self.session.db,a.id)[1]
    eq(Ch.Change(self,"thank",note.id),false);eq(ns.Notifications.All(self.session.db)[note.id].thanked,false)
end)
test("future delivery cache preserved without committing session",function()
    local x=select(1,seeded());local root=V.Copy(x.root);root.guildDelivery={["guild:1"]={version=999}}
    local before=V.Copy(root);eq(Ch.New(x.context,root,roster),nil);assert(V.Same(before,root))
end)
test("invalid queue status rejects atomic checkpoint",function()
    local x,y,id=seeded();Ch.Change(x,"thank",id);local before=V.Copy(x.root)
    local bad=V.Copy(x.delivery);bad.outbox[id].status="pretend_received"
    eq(Ch.Commit(x,x.session,bad),false);assert(V.Same(before,x.root))
end)
test("pending conflicts hide thanks and never generate false alerts",function()
    local x,y,id=seeded();receive(y,x,envelope(x,"thank",y,id))
    local conflict=fresh(a);G.AddIncident(conflict.session,x.session.incidents.i)
    G.Claim(conflict.session,{id="other",guildId="guild:1",enemyId="Enemy-Forever",avenger=a,occurredAt=200,incidentIds={"i"}})
    assert(state(conflict,y));eq(#D.View(y.delivery,y.session).notifications,0)
    local _,v,t=D.Alerts(y.delivery,y.session);eq(#v,0);eq(#t,0)
end)
test("thank receipt never changes reputation",function()
    local x,y,id=seeded();local before=ns.Reputation.Ranking(y.session.db)[1].reputation
    receive(y,x,envelope(x,"thank",y,id));eq(ns.Reputation.Ranking(y.session.db)[1].reputation,before)
end)
test("delivery capacity fails without consuming voluntary choice",function()
    local x,y,id=seeded()
    for i=1,D.limit do x.delivery.outbox["old"..i]={notificationId="old"..i,claimId="old",fromId=a.id,toId=b.id,status="delivered"} end
    eq(Ch.Change(x,"thank",id),false);eq(ns.Notifications.All(x.session.db)[id].thanked,false)
end)
test("mismatched saved delivery cannot masquerade as received",function()
    local x,y,id=seeded();Ch.Change(x,"thank",id)
    x.delivery.outbox[id].toId=z.id;x.delivery.outbox[id].status="delivered"
    eq(D.View(x.delivery,x.session).notifications[1].deliveryStatus,"local");eq(#D.Pending(x.delivery,x.session),0)
end)
test("multiple victims get separate voluntary thanks",function()
    local x,y,id=seeded();local third=fresh(z)
    G.AddIncident(third.session,{id="i2",guildId="guild:1",enemy=actor("Enemy"),victim=z,occurredAt=250,source="observed",location={zone="Elwynn"}})
    state(third,y);G.Claim(y.session,{id="v2",guildId="guild:1",enemyId="Enemy-Forever",avenger=b,occurredAt=300,incidentIds={"i2"}})
    state(y,third);local id2=ns.Notifications.List(third.session.db,z.id)[1].id
    Ch.Change(x,"thank",id);Ch.Change(third,"thank",id2)
    receive(y,x,envelope(x,"thank",y,id))
    local e=envelope(third,"thank",y,id2);e.claimId="v2";assert(receive(y,third,e))
    eq(V.Count(y.delivery.inbox),2)
end)
return {passed=count}
